#!/usr/bin/env python3
"""Flatten a CSS-variable SVG into per-theme copies Affinity Designer can open.

Charts under assets/images/ carry their colour as custom properties — a
`:root`/`svg` block for light, a `@media (prefers-color-scheme: dark)` block
for dark. Browsers resolve both. Affinity's SVG importer parses the class rules
but implements no custom properties, so every `var()` reference collapses to
black or to no paint at all, and the whole graphic imports monotone.

This resolves the variables to literals, drops the media query, and writes one
file per theme:

    python3 bin/flatten-svg-vars.py assets/images/dreyfus-confidence-competence.svg
    -> _design/dreyfus-confidence-competence-light.svg
    -> _design/dreyfus-confidence-competence-dark.svg

The outputs are working copies for editing, not build inputs — the var-based
file under assets/images/ stays the one the site serves.
"""
import argparse
import pathlib
import re
import sys

DARK_AT_RULE = "@media (prefers-color-scheme: dark)"

STYLE_RE = re.compile(r"(<style[^>]*>)(.*?)(</style>)", re.DOTALL)
CSS_COMMENT_RE = re.compile(r"/\*.*?\*/", re.DOTALL)
CUSTOM_PROP_RE = re.compile(r"--([\w-]+)\s*:\s*([^;}]+?)\s*(?=[;}])")
# var(--name) or var(--name, fallback); the fallback may itself hold commas.
VAR_RE = re.compile(r"var\(\s*--([\w-]+)\s*(?:,\s*(.+?)\s*)?\)")
EMPTY_RULE_RE = re.compile(r"[^{}]+\{\s*\}\s*")


def brace_block(text, start):
    """Return (open_index, end_index) of the {...} block starting at/after start.

    end_index is one past the matching close brace. Raises if unbalanced.
    """
    open_i = text.index("{", start)
    depth = 0
    for i in range(open_i, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return open_i, i + 1
    raise ValueError("unbalanced braces in <style> block")


def split_themes(css):
    """Split style text into (light_css, dark_css_fragment).

    The dark fragment is the body of the prefers-color-scheme block; the light
    text is everything else, with that block removed.
    """
    idx = css.find(DARK_AT_RULE)
    if idx == -1:
        return css, ""
    open_i, end_i = brace_block(css, idx)
    dark = css[open_i + 1:end_i - 1]
    light = css[:idx] + css[end_i:]
    return light, dark


def collect_props(css):
    return {name: value for name, value in CUSTOM_PROP_RE.findall(css)}


def resolve(palette, max_passes=10):
    """Resolve var() references between custom properties themselves."""
    resolved = dict(palette)
    for _ in range(max_passes):
        changed = False
        for key, value in resolved.items():
            new = substitute(value, resolved, strict=False)
            if new != value:
                resolved[key] = new
                changed = True
        if not changed:
            break
    return resolved


def substitute(text, palette, strict=True, origin=""):
    """Replace every var(--x) with its literal value."""
    missing = []

    def repl(match):
        name, fallback = match.group(1), match.group(2)
        if name in palette:
            return palette[name]
        if fallback is not None:
            return fallback
        missing.append(name)
        return match.group(0)

    out = VAR_RE.sub(repl, text)
    if missing and strict:
        raise SystemExit(
            f"{origin}: no value for {sorted(set('--' + m for m in missing))} — "
            "define it in the light block, or give the reference a fallback"
        )
    return out


def strip_custom_props(css):
    """Remove custom-property declarations, then any rule left empty."""
    css = re.sub(r"--[\w-]+\s*:\s*[^;}]+;?", "", css)
    while True:
        stripped = EMPTY_RULE_RE.sub("", css)
        if stripped == css:
            return css
        css = stripped


def tidy(css):
    """Collapse the blank lines and restore the indent the removals ate."""
    css = re.sub(r"[ \t]+\n", "\n", css)
    css = re.sub(r"\n{3,}", "\n\n", css)
    lines = [("    " + ln if ln and not ln.startswith(" ") else ln)
             for ln in css.split("\n")]
    return "\n".join(lines).strip("\n").rstrip()


def flatten(svg, palette, theme, source):
    match = STYLE_RE.search(svg)
    if not match:
        raise SystemExit(f"{source}: no <style> block — nothing to flatten")

    open_tag, css, close_tag = match.groups()
    light_css, _ = split_themes(css)
    light_css = CSS_COMMENT_RE.sub("", light_css)
    light_css = strip_custom_props(light_css)
    light_css = substitute(light_css, palette, origin=f"{source} <style>")

    banner = (f"    /* {theme} rendering, flattened from {source.name} for editing.\n"
              f"       Generated by bin/flatten-svg-vars.py — do not hand-edit. */\n")
    new_style = f"{open_tag}\n{banner}{tidy(light_css)}\n  {close_tag}"

    # The style block is rebuilt above; the body still holds var() in
    # presentation attributes, so substitute either side of it.
    head = substitute(svg[:match.start()], palette, origin=f"{source} (before <style>)")
    tail = substitute(svg[match.end():], palette, origin=f"{source} (after <style>)")
    out = head + new_style + tail

    leftover = VAR_RE.search(out)
    if leftover:
        raise SystemExit(f"{source}: unresolved {leftover.group(0)} survived flattening")
    if DARK_AT_RULE in out:
        raise SystemExit(f"{source}: dark media query survived flattening")
    return out


def process(path, out_dir):
    svg = path.read_text()
    match = STYLE_RE.search(svg)
    if not match:
        raise SystemExit(f"{path}: no <style> block — nothing to flatten")

    light_css, dark_css = split_themes(match.group(2))
    light = resolve(collect_props(light_css))
    if not light:
        raise SystemExit(f"{path}: no custom properties found — already flat?")
    # Dark overrides light rather than replacing it, so a partial dark block
    # inherits every token it does not restate.
    dark = resolve({**light, **collect_props(dark_css)})

    written = []
    for theme, palette in (("Light", light), ("Dark", dark)):
        if theme == "Dark" and not dark_css:
            print(f"  {path.name}: no {DARK_AT_RULE} block, skipping dark")
            continue
        out_path = out_dir / f"{path.stem}-{theme.lower()}.svg"
        out_path.write_text(flatten(svg, palette, theme, path))
        written.append((out_path, palette))

    for out_path, palette in written:
        print(f"  wrote {out_path} ({out_path.stat().st_size} bytes)")
        for name in sorted(palette):
            print(f"      --{name}: {palette[name]}")
    return [p for p, _ in written]


def main():
    parser = argparse.ArgumentParser(
        description="Flatten CSS custom properties in an SVG into per-theme copies."
    )
    parser.add_argument("svg", nargs="+", type=pathlib.Path,
                        help="SVG file(s) using var() for colour")
    parser.add_argument("-o", "--out-dir", type=pathlib.Path,
                        default=pathlib.Path("_design"),
                        help="where to write the flattened copies (default: _design)")
    args = parser.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)
    for path in args.svg:
        if not path.is_file():
            raise SystemExit(f"{path}: not a file")
        print(path)
        process(path, args.out_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main())
